// A 12-point seal used as the verified badge.
const SEAL = (() => {
  const pts = [];
  for (let i = 0; i < 24; i++) {
    const a = (i / 24) * Math.PI * 2 - Math.PI / 2;
    const r = i % 2 ? 9.4 : 11;
    pts.push(`${(12 + Math.cos(a) * r).toFixed(2)},${(12 + Math.sin(a) * r).toFixed(2)}`);
  }
  return `M${pts.join('L')}Z`;
})();

export function verifiedBadge(size = 16) {
  return `<svg class="verified" width="${size}" height="${size}" viewBox="0 0 24 24" role="img" aria-label="Verified artist"><path d="${SEAL}" fill="currentColor" stroke="currentColor" stroke-width="1.4" stroke-linejoin="round"/><path class="verified-check" d="m8 12.3 2.7 2.7L16 9.6" fill="none" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round"/></svg>`;
}

